"""
Insight Model

AI-generated and rule-based financial insights for users.

Schema Design:
    - Insight: Main insight record (e.g., "You're spending $45/week on coffee")
    - InsightTransaction: Junction table linking insights to specific transactions

Compare to .NET:
    [Table("insights", Schema = "cardora")]
    [Index(nameof(UserId), nameof(CreatedAt))]
    public class Insight
    {
        public Guid Id { get; set; }
        public Guid UserId { get; set; }
        public string InsightType { get; set; }
        public string Title { get; set; }
        public string Description { get; set; }
        public decimal ImpactScore { get; set; }
        public decimal? PotentialSavings { get; set; }
        public DateTime CreatedAt { get; set; }
        public DateTime? DismissedAt { get; set; }

        public User User { get; set; }
        public List<InsightTransaction> InsightTransactions { get; set; }
    }
"""

import uuid
from sqlalchemy import Column, String, Integer, ForeignKey, Numeric, DateTime, Text, Index
from sqlalchemy.dialects.postgresql import UUID
from sqlalchemy.orm import relationship
from datetime import datetime, timezone

from app.core.database import Base


class Insight(Base):
    """
    Financial insight generated by AI or rule-based algorithms

    Represents actionable financial advice for users based on their spending patterns.

    Insight Types:
    - subscription_audit: Recurring subscriptions that might be unused
    - coffee_habit: Frequent small purchases at coffee shops
    - weekend_spending: High spending on weekends
    - category_trend: Unusual spending trends in a category
    - merchant_concentration: Too much spending at one merchant
    - anomaly_detection: Unusual transactions detected
    - ai_personalized: AI-generated personalized insight

    Example:
        "You're spending $180/month on coffee ☕"
        "3 subscriptions you haven't used in 60 days"
    """

    __tablename__ = "insights"
    __table_args__ = (
        # ═══════════════════════════════════════════════════════════════
        # PERFORMANCE INDEXES
        # ═══════════════════════════════════════════════════════════════

        # Index 1: User + Created Date (for fetching recent insights)
        # Query: "Show all insights for user, most recent first"
        Index(
            "ix_insights_user_created",
            "user_id", "created_at",
            postgresql_using="btree"
        ),

        # Index 2: User + Not Dismissed (for active insights)
        # Query: "Show only non-dismissed insights for user"
        Index(
            "ix_insights_user_active",
            "user_id", "dismissed_at",
            postgresql_using="btree"
        ),

        {"schema": "cardora"}
    )

    # ═══════════════════════════════════════════════════════════════
    # PRIMARY KEY
    # ═══════════════════════════════════════════════════════════════

    id = Column(
        UUID(as_uuid=True),
        primary_key=True,
        default=uuid.uuid4,
        nullable=False
    )

    # ═══════════════════════════════════════════════════════════════
    # FOREIGN KEYS
    # ═══════════════════════════════════════════════════════════════

    user_id = Column(
        UUID(as_uuid=True),
        ForeignKey("cardora.users.id"),
        nullable=False
    )
    # Every insight belongs to a user

    # ═══════════════════════════════════════════════════════════════
    # INSIGHT CONTENT
    # ═══════════════════════════════════════════════════════════════

    insight_type = Column(
        String(50),
        nullable=False
    )
    # Type of insight:
    # - "subscription_audit"
    # - "coffee_habit"
    # - "weekend_spending"
    # - "category_trend"
    # - "merchant_concentration"
    # - "anomaly_detection"
    # - "ai_personalized"

    title = Column(
        String(200),
        nullable=False
    )
    # Short, catchy title for the insight
    # Example: "You're spending $180/month on coffee ☕"
    # Max 200 chars for UI display

    description = Column(
        Text,
        nullable=False
    )
    # Detailed explanation of the insight
    # Example: "Over the past 3 months, you've visited Starbucks 45 times..."
    # Can be longer, includes actionable advice

    # ═══════════════════════════════════════════════════════════════
    # METADATA & SCORING
    # ═══════════════════════════════════════════════════════════════

    impact_score = Column(
        Integer,
        nullable=False,
        default=5
    )
    # How important is this insight? (1-10)
    # 10 = High impact (big potential savings or issue)
    # 5 = Medium impact
    # 1 = Low impact (nice to know)
    # Used for sorting insights by importance

    potential_savings = Column(
        Numeric(10, 2),
        nullable=True
    )
    # Estimated monthly savings if user acts on this insight
    # Example: 45.00 (could save $45/month)
    # NULL if not applicable (e.g., informational insights)

    # ═══════════════════════════════════════════════════════════════
    # TIMESTAMPS
    # ═══════════════════════════════════════════════════════════════

    created_at = Column(
        DateTime(timezone=True),
        default=lambda: datetime.now(timezone.utc),
        nullable=False
    )
    # When insight was generated

    dismissed_at = Column(
        DateTime(timezone=True),
        nullable=True
    )
    # When user dismissed this insight
    # NULL = insight still active
    # NOT NULL = user dismissed it, don't show again

    # ═══════════════════════════════════════════════════════════════
    # RELATIONSHIPS
    # ═══════════════════════════════════════════════════════════════

    # Relationship to User (Many-to-One)
    user = relationship(
        "User",
        back_populates="insights"
    )

    # Relationship to Transactions (Many-to-Many through InsightTransaction)
    # This links insights to the specific transactions they're based on
    insight_transactions = relationship(
        "InsightTransaction",
        back_populates="insight",
        cascade="all, delete-orphan"
    )

    # ═══════════════════════════════════════════════════════════════
    # STRING REPRESENTATION
    # ═══════════════════════════════════════════════════════════════

    def __repr__(self):
        return f"<Insight {self.insight_type}: {self.title}>"


class InsightTransaction(Base):
    """
    Junction table linking Insights to Transactions

    Many-to-Many relationship:
    - One insight can reference multiple transactions
    - One transaction can be referenced by multiple insights

    Example:
        Insight: "You're spending $180/month on coffee"
        Transactions: [txn1, txn2, txn3, ...] (all coffee purchases)
    """

    __tablename__ = "insight_transactions"
    __table_args__ = (
        # Index for looking up transactions for an insight
        Index(
            "ix_insight_transactions_insight",
            "insight_id",
            postgresql_using="btree"
        ),

        # Index for looking up insights for a transaction
        Index(
            "ix_insight_transactions_transaction",
            "transaction_id",
            postgresql_using="btree"
        ),

        {"schema": "cardora"}
    )

    # ═══════════════════════════════════════════════════════════════
    # PRIMARY KEY
    # ═══════════════════════════════════════════════════════════════

    id = Column(
        UUID(as_uuid=True),
        primary_key=True,
        default=uuid.uuid4,
        nullable=False
    )

    # ═══════════════════════════════════════════════════════════════
    # FOREIGN KEYS
    # ═══════════════════════════════════════════════════════════════

    insight_id = Column(
        UUID(as_uuid=True),
        ForeignKey("cardora.insights.id"),
        nullable=False
    )

    transaction_id = Column(
        UUID(as_uuid=True),
        ForeignKey("cardora.transactions.id"),
        nullable=False
    )

    # ═══════════════════════════════════════════════════════════════
    # RELATIONSHIPS
    # ═══════════════════════════════════════════════════════════════

    insight = relationship(
        "Insight",
        back_populates="insight_transactions"
    )

    transaction = relationship(
        "Transaction",
        back_populates="insight_transactions"
    )

    def __repr__(self):
        return f"<InsightTransaction insight={self.insight_id} transaction={self.transaction_id}>"
